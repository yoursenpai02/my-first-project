    // Newsletter form submission
    document.getElementById('newsletterForm').addEventListener('submit', function(e) {
        e.preventDefault();

        const email = this.querySelector('input[type="email"]').value;
        const button = this.querySelector('button[type="submit"]');
        const originalText = button.innerHTML;

        if (!email) {
            alert('Please enter your email address.');
            return;
        }

        if (!email.match(/^[^\s@]+@[^\s@]+\.[^\s@]+$/)) {
            alert('Please enter a valid email address.');
            return;
        }

        // Show loading state
        button.innerHTML = '<i class="fas fa-spinner fa-spin"></i>';
        button.disabled = true;

        // Simulate API call (in real app, this would make an AJAX request)
        setTimeout(function() {
            // Show success message
            showMessage('Thank you for subscribing to our newsletter!', 'success');

            // Reset form
            e.target.reset();
            button.innerHTML = originalText;
            button.disabled = false;
        }, 2000);
    });

    // Show message function (global)
    function showMessage(message, type = 'info') {
        const alertClass = type === 'success' ? 'alert-success' :
                           type === 'error' ? 'alert-danger' :
                           type === 'warning' ? 'alert-warning' : 'alert-info';

        const alertHtml = `
            <div class="alert ${alertClass} alert-dismissible fade show position-fixed"
                 style="top: 80px; right: 20px; z-index: 9999; max-width: 400px;"
                 role="alert">
                ${message}
                <button type="button" class="btn-close" data-bs-dismiss="alert"></button>
            </div>
        `;

        // Remove existing alerts
        document.querySelectorAll('#message-container .alert').forEach(alert => alert.remove());

        // Add new alert
        const container = document.getElementById('message-container');
        if (container) {
            container.insertAdjacentHTML('beforeend', alertHtml);

            // Auto-remove after 5 seconds
            setTimeout(() => {
                const newAlert = container.querySelector('.alert');
                if (newAlert) {
                    newAlert.remove();
                }
            }, 5000);
        }
    }

    // Back to top button functionality
    const backToTopButton = document.getElementById('backToTop');

    window.addEventListener('scroll', function() {
        if (window.pageYOffset > 300) {
            backToTopButton.style.display = 'block';
        } else {
            backToTopButton.style.display = 'none';
        }
    });

    backToTopButton.addEventListener('click', function(e) {
        e.preventDefault();
        window.scrollTo({
            top: 0,
